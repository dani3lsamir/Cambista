let current = 'es';

// setting: 'system' | 'es' | 'en'
export function setLanguage(setting) {
  current = pickLanguage(setting, typeof navigator !== 'undefined' ? navigator.language : 'es');
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  return current;
}

export const lang = () => current;

// t('minAgo', { n: 5 }) -> 'hace 5 min'
export function t(key, vars) {
  const text = TEXTS[current][key] ?? TEXTS.es[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : text;
}

